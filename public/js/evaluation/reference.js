// Owned, deterministic drawings. A regression pack, NOT a Thai CCTV dataset.
export const PACK = { id: 'vision-synthetic-road-v1', width: 320, height: 180, provenance: 'Generated by this repository; no camera images or people recorded.', limitation: 'Stylised sequence variants share one renderer and projection. They test regression behaviour, not accuracy or camera transfer on real roads.' }
const conditions = ['day', 'night', 'rain', 'small', 'crowded', 'occluded']
export function referenceFrames() {
  const frames = []
  for (let sequence = 0; sequence < 12; sequence++) {
    const condition = conditions[sequence % 6]
    for (let tick = 0; tick < 16; tick++) {
      const boxes = Array.from({ length: condition === 'crowded' ? 6 : 3 }, (_, i) => {
        const cls = [3, 4, 1, 6][(i + sequence) % 4]
        const small = condition === 'small' ? 0.5 : 1
        return { track: `s${sequence}-${i}`, cls, x: 0.03 + ((sequence * 0.031 + i * 0.15 + tick * 0.018) % 0.8), y: 0.4 + (i % 3) * 0.15, w: (cls === 1 ? 0.025 : cls === 6 ? 0.12 : 0.075) * small, h: (cls === 1 ? 0.16 : 0.09) * small }
      })
      frames.push({ id: `s${sequence}-f${tick}`, group: `synthetic-sequence-${sequence}`, split: sequence < 6 ? 'development' : 'evaluation', condition, timeMs: tick * 250, boxes })
    }
  }
  for (let i = 0; i < 8; i++) frames.push({ id: `control-${i}`, group: `control-sequence-${i}`, split: i < 4 ? 'development' : 'evaluation', condition: ['empty', 'dark', 'flat', 'slate'][i % 4], timeMs: 0, boxes: [] })
  return frames
}
export function drawReference(g, frame) {
  const { width: w, height: h } = PACK
  g.fillStyle = frame.condition === 'night' || frame.condition === 'dark' ? '#10131a' : '#a6b3b7'
  g.fillRect(0, 0, w, h)
  if (frame.condition === 'flat' || frame.condition === 'dark') return
  if (frame.condition === 'slate') {
    g.fillStyle = '#202020'; g.fillRect(0, 0, w, h)
    g.fillStyle = '#bbbbbb'; g.fillRect(40, 70, 240, 8); g.fillRect(80, 100, 160, 6)
    return
  }
  g.fillStyle = frame.condition === 'night' ? '#191b22' : '#535961'; g.fillRect(0, 60, w, h - 60)
  g.fillStyle = '#dfd5b5'
  for (let x = 0; x < w; x += 40) g.fillRect(x, 112, 20, 2)
  for (const b of frame.boxes) {
    const x = b.x * w, y = b.y * h, bw = b.w * w, bh = b.h * h
    g.fillStyle = ['#d2d5d9', '#c37d54', '#9cab84', '#b5a4c7'][b.cls % 4]
    g.fillRect(x, y, bw, bh)
    g.fillStyle = '#142233'; g.fillRect(x + bw * 0.2, y + bh * 0.15, bw * 0.6, bh * 0.3)
  }
  if (frame.condition === 'occluded') { g.fillStyle = '#858177'; g.fillRect(w * 0.4, h * 0.35, w * 0.04, h * 0.6) }
  if (frame.condition === 'rain') {
    g.strokeStyle = '#a3aab4'; g.beginPath()
    for (let x = 0; x < w; x += 13) { g.moveTo(x, 0); g.lineTo(x - 28, h) }
    g.stroke()
  }
}
